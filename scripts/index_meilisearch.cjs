/**
 * Derives a Meilisearch document from a raw record, generating a slug from
 * name/title/service when one isn't present. Shared by both the required
 * and best-effort loaders so the slug-derivation logic exists exactly once.
 */
function buildDocument(doc, baseNameForFile, docIndex, totalInFile, dataType) {
  let itemSlug = doc.slug;
  const itemIdentifierLog =
    totalInFile > 1 ? `${baseNameForFile}[${docIndex}]` : baseNameForFile;

  if (!itemSlug) {
    const slugSource = doc.name || doc.title || doc.service || baseNameForFile;
    if (slugSource) {
      itemSlug = slugSource
        .toString()
        .toLowerCase()
        .replace(/\s+/g, '-')
        .replace(/[^\w-]+/g, '')
        .replace(/--+/g, '-')
        .replace(/^-+/, '')
        .replace(/-+$/, '');
      if (totalInFile > 1 && !doc.name && !doc.title && !doc.service) {
        itemSlug = `${itemSlug}-${docIndex}`;
      }
    } else {
      itemSlug = `${baseNameForFile}${totalInFile > 1 ? `-${docIndex}` : ''}`;
    }
    console.log(
      `Document from ${itemIdentifierLog} missing 'slug'. Generated slug: ${itemSlug}`
    );
  }

  return { ...doc, id: doc.id || itemSlug, slug: itemSlug, type: dataType };
}

/**
 * Loads and compiles a data source's tracked JSON Schema once, so every file
 * in that source is validated against the exact same compiled validator
 * instead of re-parsing/re-compiling per file. A schema that fails to read,
 * parse, or compile is fatal — it's the contract; a broken contract can't be
 * silently skipped.
 */
async function compileRequiredSchema(schemaPath) {
  let schema;
  try {
    schema = JSON.parse(await fs.readFile(schemaPath, 'utf-8'));
  } catch (error) {
    throw new FatalIndexingError(
      `Failed to read or parse the required schema ${schemaPath}: ${error.message}`
    );
  }
  const ajv = new Ajv({ allErrors: true, strict: false });
  try {
    return ajv.compile(schema);
  } catch (error) {
    throw new FatalIndexingError(
      `Failed to compile the required schema ${schemaPath}: ${error.message}`
    );
  }
}

/**
 * Validates an entire parsed file's contents against the source's compiled
 * schema in one shot — the schema itself is an array schema
 * (`services.schema.json`'s `type: "array"`, `items: {...}`), so this
 * checks every record's complete shape (all required fields, slug/URL
 * patterns, no unknown properties) in the same pass the sync pipeline's own
 * write.ts uses, not a hand-maintained partial re-implementation of it. A
 * syntactically valid but schema-invalid record — e.g. one carrying only
 * `service` and `slug` — fails here, before any Meilisearch contact.
 */
function assertSatisfiesSchema(validate, parsed, filePath, schemaPath) {
  if (validate(parsed)) return;
  const detail = (validate.errors ?? [])
    .map(e => `${e.instancePath || '/'} ${e.message}`)
    .join('; ');
  throw new FatalIndexingError(
    `Required file ${filePath} does not satisfy ${schemaPath}: ${detail}`
  );
}

/**
 * Loads, parses, and validates every file for a `requireNonEmpty` data
 * source. ANY problem is fatal: a missing directory, zero files, a file
 * that fails to read or parse, a record with an invalid shape, or zero
 * records combined. Nothing is logged-and-skipped here — that behavior is
 * exactly what let an empty or malformed generated snapshot through before.
 *
 * Called during preflight, before Meilisearch is contacted at all, so a bad
 * snapshot can never reach deleteIndex/createIndex/updateSettings/
 * addDocuments/deleteDocuments.
 */
async function loadRequiredDocuments(dataSource) {
  // A required source is either ONE file (isFile) or a directory of files.
  // Generated single-file sources (src/data/directory/departments.json,
  // executive.json) use the former; src/data/services/ uses the latter.
  let baseDir;
  let jsonFiles;

  if (dataSource.isFile) {
    baseDir = path.dirname(dataSource.dataPath);
    try {
      await fs.access(dataSource.dataPath);
    } catch {
      throw new FatalIndexingError(
        `Required file ${dataSource.dataPath} not found for type ` +
          `"${dataSource.dataType}". This data is generated by the CMS sync ` +
          'script (see package.json) and never committed — run it before indexing.'
      );
    }
    jsonFiles = [path.basename(dataSource.dataPath)];
  } else {
    let filesInDir;
    try {
      filesInDir = await fs.readdir(dataSource.dataPath);
    } catch (error) {
      if (error.code === 'ENOENT') {
        throw new FatalIndexingError(
          `Data directory ${dataSource.dataPath} not found for type ` +
            `"${dataSource.dataType}". This data is generated by the CMS sync ` +
            'script (see package.json) and never committed — run it before indexing.'
        );
      }
      throw new FatalIndexingError(
        `Failed to read ${dataSource.dataPath}: ${error.message}`
      );
    }
    baseDir = dataSource.dataPath;
    jsonFiles = filesInDir
      .filter(f => path.extname(f).toLowerCase() === '.json')
      .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

    if (jsonFiles.length === 0) {
      throw new FatalIndexingError(
        `No generated "${dataSource.dataType}" JSON files found in ${dataSource.dataPath}. ` +
          'This data is generated by the CMS sync script (see package.json) and never ' +
          'committed — run it before indexing.'
      );
    }
  }

  // Compiled once, reused for every file in this source — see
  // compileRequiredSchema's own comment for why a missing/invalid schema is
  // itself fatal rather than silently skipped.
  const validate = dataSource.schemaPath
    ? await compileRequiredSchema(dataSource.schemaPath)
    : null;

  const documents = [];
  for (const fileName of jsonFiles) {
    const filePath = path.join(baseDir, fileName);
    let parsed;
    try {
      const fileContent = await fs.readFile(filePath, 'utf-8');
      parsed = JSON.parse(fileContent);
    } catch (error) {
      throw new FatalIndexingError(
        `Failed to read or parse required file ${filePath}: ${error.message}`
      );
    }
    if (!Array.isArray(parsed)) {
      throw new FatalIndexingError(
        `Required file ${filePath} must contain a JSON array, got ${typeof parsed}.`
      );
    }
    if (validate) {
      assertSatisfiesSchema(validate, parsed, filePath, dataSource.schemaPath);
    }

    const baseNameForFile = path.basename(fileName, '.json');
    parsed.forEach((doc, i) => {
      const document = buildDocument(
        doc,
        baseNameForFile,
        i,
        parsed.length,
        dataSource.dataType
      );
      // Provenance for the directory snapshot. Non-enumerable so it never
      // reaches Meilisearch via the `{...doc}` spread in buildDocument's
      // output.
      Object.defineProperty(document, '__sourceFile', {
        value: fileName,
        enumerable: false,
        writable: false,
      });
      documents.push(document);
    });
  }

  if (documents.length === 0) {
    throw new FatalIndexingError(
      `Generated "${dataSource.dataType}" files in ${dataSource.dataPath} contain zero ` +
        'records combined. Refusing to index: this is indistinguishable from a ' +
        'corrupted or partial snapshot.'
    );
  }

  console.log(
    `Preflight OK for "${dataSource.dataType}" (${dataSource.dataPath}): ` +
      `${jsonFiles.length} file(s), ${documents.length} record(s).`
  );
  return documents;
}

/**
 * Best-effort loader for a data source that's allowed to be legitimately
 * absent or empty (directory listings, the single websites.json file). A
 * read/parse failure for one file is logged and that file is skipped — the
 * same tolerant behavior this script has always had for these sources.
 *
 * `report`, when supplied, accumulates provenance and problems so a caller
 * can tell "loaded nothing because there was nothing" from "loaded nothing
 * because every file failed". Without it, behavior is byte-for-byte what it
 * was.
 */
async function loadOptionalDocuments(dataSource, report = null) {
  const documents = [];

  const tagAndPush = (doc, baseNameForFile, i, total, fileName) => {
    const document = buildDocument(
      doc,
      baseNameForFile,
      i,
      total,
      dataSource.dataType
    );
    Object.defineProperty(document, '__sourceFile', {
      value: fileName,
      enumerable: false,
      writable: false,
    });
    documents.push(document);
  };

  if (dataSource.isFile) {
    try {
      const filePath = dataSource.dataPath;
      const fileName = path.basename(filePath);
      const baseNameForFile = path.basename(filePath, '.json');
      const fileContent = await fs.readFile(filePath, 'utf-8');
      const parsedJson = JSON.parse(fileContent);
      const documentsFromFile = Array.isArray(parsedJson)
        ? parsedJson
        : [parsedJson];
      console.log(
        `Processing single file ${filePath} with ${documentsFromFile.length} items.`
      );
      documentsFromFile.forEach((doc, i) => {
        tagAndPush(doc, baseNameForFile, i, documentsFromFile.length, fileName);
      });
      report?.loadedFiles.push(fileName);
    } catch (error) {
      console.error(`Error processing file ${dataSource.dataPath}:`, error);
      report?.problems.push(
        `failed to read or parse ${dataSource.dataPath}: ${error.message}`
      );
    }
    return documents;
  }

  let filesInDir;
  try {
    filesInDir = await fs.readdir(dataSource.dataPath);
  } catch (error) {
    if (error.code === 'ENOENT') {
      console.warn(
        `Data directory ${dataSource.dataPath} not found for type ${dataSource.dataType}. Skipping.`
      );
      report?.problems.push(`data directory ${dataSource.dataPath} not found`);
    } else {
      console.error(
        `Error reading from directory ${dataSource.dataPath}:`,
        error
      );
      report?.problems.push(
        `failed to read directory ${dataSource.dataPath}: ${error.message}`
      );
    }
    return documents;
  }

  const excluded = new Set(dataSource.excludeFiles ?? []);
  const jsonFiles = filesInDir.filter(
    f => path.extname(f).toLowerCase() === '.json' && !excluded.has(f)
  );
  if (jsonFiles.length === 0) {
    console.log(
      `No JSON files found in ${dataSource.dataPath} for type ${dataSource.dataType}. Skipping.`
    );
    return documents;
  }
  console.log(
    `Found ${jsonFiles.length} JSON files in ${dataSource.dataPath}.`
  );

  for (const fileName of jsonFiles) {
    const filePath = path.join(dataSource.dataPath, fileName);
    const baseNameForFile = path.basename(fileName, '.json');
    try {
      const fileContent = await fs.readFile(filePath, 'utf-8');
      const parsedJson = JSON.parse(fileContent);
      const documentsFromFile = Array.isArray(parsedJson)
        ? parsedJson
        : [parsedJson];
      documentsFromFile.forEach((doc, i) => {
        tagAndPush(doc, baseNameForFile, i, documentsFromFile.length, fileName);
      });
      report?.loadedFiles.push(fileName);
    } catch (error) {
      console.error(
        `Error processing file ${fileName} (path: ${filePath}):`,
        error
      );
      report?.problems.push(
        `failed to read or parse ${fileName}: ${error.message}`
      );
    }
  }
  return documents;
}

/**
 * Loads EVERY directory_item document — the two generated required files plus
 * every tolerant file — and reports where each came from and whether the set
 * is complete.
 *
 * `complete` is false when ANY of these hold:
 *   1. the directory itself is missing or unreadable;
 *   2. zero expected files were discovered;
 *   3. an expected, non-excluded file is missing from disk;
 *   4. a file failed to read;
 *   5. a file failed to JSON-parse;
 *   6. any file was skipped for any other reason.
 *
 * Expected files come from the DECLARED manifest (DIRECTORY_EXPECTED_FILES —
 * all eight), never from the directory listing: a listing cannot report a file
 * that is gone, which is precisely the case stale reconciliation must refuse
 * to act on.
 *
 * `opts.dir` exists only so tests can point at a fixture copy. It rebases the
 * DATA FILES only, by basename; `schemaPath` is never rebased.
 */
async function loadDirectorySnapshot(opts = {}) {
  const dir = opts.dir ?? path.join(dataBasePath, 'directory');
  // Injection seam, defaulting to production. Lets the aggregate tests supply
  // a complete fixture source list on a clean checkout.
  const sources = opts.sources ?? DATA_SOURCES;
  const problems = [];
  const documents = [];
  const bySourceFile = new Map();
  const loadedFiles = [];

  const record = docs => {
    for (const d of docs) {
      documents.push(d);
      const file = d.__sourceFile ?? '(unknown)';
      bySourceFile.set(file, (bySourceFile.get(file) ?? 0) + 1);
    }
  };

  for (const source of sources.filter(
    s => s.dataType === 'directory_item' && s.isFile
  )) {
    // Rebasing is a filename-only operation: keep the source's basename, take
    // the directory from `dir`. `schemaPath` is deliberately NOT rebased — the
    // tracked JSON Schema is the contract and always comes from the
    // repository, never from a fixture copy.
    const dataPath = path.join(dir, path.basename(source.dataPath));

    // Required sources THROW on any problem — intentional and unchanged. A
    // missing or invalid generated file is fatal, not merely incomplete.
    record(await loadRequiredDocuments({ ...source, dataPath }));
    loadedFiles.push(path.basename(source.dataPath));
  }

  const [tolerant] = sources.filter(
    s => s.dataType === 'directory_item' && !s.isFile
  );
  const report = { loadedFiles: [], problems: [] };
  record(await loadOptionalDocuments({ ...tolerant, dataPath: dir }, report));
  loadedFiles.push(...report.loadedFiles);
  problems.push(...report.problems);

  const expectedTolerant = tolerant.expectedFiles ?? [];
  if (expectedTolerant.length === 0) {
    problems.push('no expected tolerant directory files are declared');
  }
  for (const file of expectedTolerant) {
    if (!report.loadedFiles.includes(file)) {
      problems.push(`expected directory file ${file} was not loaded`);
    }
  }

  // The snapshot's expectation is the COMPLETE eight-file manifest; the
  // required loop above has already thrown if either generated file was
  // missing, so reaching here means both loaded.
  for (const file of DIRECTORY_EXPECTED_FILES) {
    if (!loadedFiles.includes(file)) {
      problems.push(
        `expected directory file ${file} is missing from the snapshot`
      );
    }
  }

  return {
    documents,
    bySourceFile,
    expectedFiles: DIRECTORY_EXPECTED_FILES,
    loadedFiles,
    complete: problems.length === 0,
    problems,
  };
}

/**
 * Meilisearch indexes every document into ONE index keyed by `slug`, so two
 * directory documents sharing a slug means one silently overwrites the other
 * and one office becomes unsearchable.
 *
 * Runs over the COMPLETE loaded snapshot, which is why it lives here and not
 * only in the sync: `npm run cms:fetch -- --only=departments` cannot see
 * executive.json (query isolation is deliberate), so a collision introduced
 * that way is only detectable at index time.
 *
 * CROSS-SOURCE collisions only. Measured across the 8 current directory files:
 * 612 documents, 611 distinct slugs, exactly one collision — intra-file, in
 * house_members.json, from a literally duplicated record. Failing on that
 * pre-existing data defect would break indexing today for something this
 * branch does not own.
 *
 * Deliberately NOT extended to directory ↔ website collisions: `slug` is
 * index-wide identity and 289 such collisions already exist (websites.json is
 * derived from these very files), so that gate would fail on the first run and
 * would require changing Government Websites — out of scope.
 */
function assertUniqueDirectorySlugs(snapshot) {
  const bySlug = new Map();
  for (const doc of snapshot.documents) {
    const file = doc.__sourceFile ?? '(unknown)';
    if (!bySlug.has(doc.slug)) bySlug.set(doc.slug, new Set());
    bySlug.get(doc.slug).add(file);
  }

  const collisions = [...bySlug]
    .filter(([, files]) => files.size > 1)
    .map(([slug, files]) => `${slug} (${[...files].sort().join(' + ')})`);

  if (collisions.length > 0) {
    throw new FatalIndexingError(
      `${collisions.length} slug(s) appear in more than one directory source: ` +
        `${collisions.join('; ')}. Meilisearch keys its single index by slug, so ` +
        'these records would overwrite each other and one would become unsearchable. ' +
        'Refusing to index.'
    );
  }
}

/**
 * Awaits a Meilisearch task-returning call and verifies the task actually
 * finished `succeeded` — a request that's merely *accepted* (enqueued) is
 * not proof the mutation happened. Any other terminal status, or a
 * synchronous request failure, propagates as a thrown error: nothing in
 * this script may catch a required Meilisearch failure and continue.
 */
async function waitForSuccess(taskPromise, label) {
  const task = await taskPromise;
  const result = await client.tasks.waitForTask(task.taskUid);
  if (result.status !== 'succeeded') {
    const detail = result.error ? ` — ${result.error.message}` : '';
    throw new MeilisearchTaskError(
      `${label} did not succeed: task ${task.taskUid} ended with status "${result.status}"${detail}`
    );
  }
  console.log(`${label} succeeded (task ${task.taskUid}).`);
  return result;
}

/**
 * After successfully indexing the current service documents, removes any
 * previously-indexed "service"-type document whose slug is no longer in the
 * current generated set — a category retired or a service removed/renamed
 * in the CMS. Scoped strictly to `type = service`: a non-service document
 * can never be a candidate for removal here, by construction of the filter.
 *
 * Only meaningful in update mode against a pre-existing index: a freshly
 * created index (first run, or just recreated by --reset) cannot have any
 * stale documents in it.
 */
async function reconcileStaleServiceDocuments(index, currentServiceDocuments) {
  const currentSlugs = new Set(currentServiceDocuments.map(d => d.slug));
  const staleSlugs = [];
  const pageSize = 1000;
  let offset = 0;

  for (;;) {
    const page = await index.getDocuments({
      filter: 'type = service',
      fields: ['slug'],
      limit: pageSize,
      offset,
    });
    for (const doc of page.results) {
      if (!currentSlugs.has(doc.slug)) staleSlugs.push(doc.slug);
    }
    offset += page.results.length;
    if (page.results.length === 0 || offset >= page.total) break;
  }

  if (staleSlugs.length === 0) {
    console.log('No stale service documents to remove.');
    return;
  }

  console.log(
    `Removing ${staleSlugs.length} stale service document(s): ${staleSlugs.join(', ')}`
  );
  await waitForSuccess(
    index.deleteDocuments(staleSlugs),
    'Stale service document removal'
  );
}

/**
 * After successfully indexing the current directory documents, removes any
 * previously-indexed "directory_item" document whose slug is no longer in the
 * current snapshot — a department or executive office renamed or deleted in
 * TalaCMS. Scoped strictly to `type = directory_item`: a service or website
 * document can never be a candidate for removal here, by construction of the
 * filter.
 *
 * `snapshot` MUST be the full directory snapshot, covering EVERY directory
 * source — constitutional, diplomatic, judicial, legislative and the two
 * orphaned member files all carry the same `type` and would otherwise all
 * look stale.
 *
 * When `snapshot.complete` is false, nothing runs: not the paged query, not
 * the deletion. An incomplete snapshot cannot distinguish "this record was
 * removed from the CMS" from "this file failed to parse this run", and
 * deleting on that ambiguity is exactly the fail-open behavior this function
 * exists to prevent.
 *
 * `io.waiter` exists only so tests can observe task completion without the
 * module-level Meilisearch client that waitForSuccess closes over.
 *
 * Only meaningful in update mode against a pre-existing index: a freshly
 * created index (first run, or just recreated by --reset) cannot have any
 * stale documents in it.
 */
async function reconcileStaleDirectoryDocuments(index, snapshot, io = {}) {
  const waiter = io.waiter ?? waitForSuccess;

  if (!snapshot.complete) {
    console.log(
      'Skipping stale directory reconciliation — the directory snapshot is ' +
        `incomplete: ${snapshot.problems.join('; ')}`
    );
    return;
  }

  const currentSlugs = new Set(snapshot.documents.map(d => d.slug));
  const staleSlugs = [];
  const pageSize = 1000;
  let offset = 0;

  for (;;) {
    const page = await index.getDocuments({
      filter: 'type = directory_item',
      fields: ['slug'],
      limit: pageSize,
      offset,
    });
    for (const doc of page.results) {
      if (!currentSlugs.has(doc.slug)) staleSlugs.push(doc.slug);
    }
    offset += page.results.length;
    if (page.results.length === 0 || offset >= page.total) break;
  }

  if (staleSlugs.length === 0) {
    console.log('No stale directory documents to remove.');
    return;
  }

  console.log(
    `Removing ${staleSlugs.length} stale directory document(s): ${staleSlugs.join(', ')}`
  );
  await waiter(
    index.deleteDocuments(staleSlugs),
    'Stale directory document removal'
  );
}

/**
 * Builds the complete document set to submit to Meilisearch, with ZERO
 * contact with Meilisearch. Extracted from main() so the final aggregate —
 * not merely its parts — can be asserted in tests.
 *
 * Every `directory_item` document enters through loadDirectorySnapshot() and
 * NOWHERE ELSE: both generic loops explicitly skip directory sources. Loading
 * them generically as well would double every directory document, because the
 * generic loops select on `requireNonEmpty` alone and the directory sources
 * span both sides of that flag.
 *
 * Order is [required, directory, optional] — NOT [required, optional,
 * directory]. addDocuments lets the last duplicate primary key win, and the
 * pre-existing directory↔website slug collisions currently resolve to the
 * website document. Appending the snapshot last would silently invert that.
 *
 * `sources` and `opts.directoryDir` are injection seams, defaulting to
 * production values. They exist so the aggregate tests can run on a CLEAN
 * checkout: src/data/services/*.json and the two generated directory files are
 * gitignored, and a test that depends on them would be skipped exactly where
 * this invariant most needs proving. Same pattern the existing `service`
 * preflight tests already use via makeServicesDir() + an explicit dataPath.
 */
async function assemblePreflightDocuments(sources = DATA_SOURCES, opts = {}) {
  const isDirectorySource = s => s.dataType === 'directory_item';

  const requiredDocuments = [];
  for (const dataSource of sources.filter(
    s => s.requireNonEmpty && !isDirectorySource(s)
  )) {
    console.log(
      `Preflighting required data source "${dataSource.dataType}" from ${dataSource.dataPath}`
    );
    requiredDocuments.push(...(await loadRequiredDocuments(dataSource)));
  }

  const optionalDocuments = [];
  for (const dataSource of sources.filter(
    s => !s.requireNonEmpty && !isDirectorySource(s)
  )) {
    optionalDocuments.push(...(await loadOptionalDocuments(dataSource)));
  }

  // The single entry point for every directory_item document.
  const directorySnapshot = await loadDirectorySnapshot({
    dir: opts.directoryDir,
    sources,
  });
  assertUniqueDirectorySlugs(directorySnapshot);
  console.log(
    `Preflight OK for "directory_item": ${directorySnapshot.bySourceFile.size} file(s), ` +
      `${directorySnapshot.documents.length} record(s)` +
      (directorySnapshot.complete
        ? '.'
        : ' — INCOMPLETE, stale reconciliation will be skipped.')
  );

  const allDocumentsToIndex = [
    ...requiredDocuments,
    ...directorySnapshot.documents,
    ...optionalDocuments,
  ];
  console.log(
    `Preflight complete: ${allDocumentsToIndex.length} total document(s) ready to index.`
  );

  return { allDocumentsToIndex, requiredDocuments, directorySnapshot };
}

async function main() {
  console.log(
    `Starting Meilisearch indexing script for the single index: ${SINGLE_INDEX_NAME}`
  );

  // ---- Preflight: load and validate every data source, with ZERO contact
  // with Meilisearch. A required source's failure throws here and nothing
  // below this block ever runs. ----
  const { allDocumentsToIndex, requiredDocuments, directorySnapshot } =
    await assemblePreflightDocuments();

  // ---- From here on, every Meilisearch call either succeeds or throws.
  // Nothing below catches a required failure and returns normally. ----
  const health = await client.health();
  console.log('Meilisearch server is healthy:', health);

  let indexExistedBefore = true;
  try {
    await client.getIndex(SINGLE_INDEX_NAME);
  } catch (error) {
    if (error.cause && error.cause.code === 'index_not_found') {
      indexExistedBefore = false;
    } else {
      throw error;
    }
  }

  if (indexExistedBefore && RESET_INDEX) {
    console.log(
      `Index '${SINGLE_INDEX_NAME}' exists and --reset flag was provided. Deleting index...`
    );
    await waitForSuccess(
      client.deleteIndex(SINGLE_INDEX_NAME),
      'Index deletion'
    );
  }

  const indexIsFresh = !indexExistedBefore || RESET_INDEX;

  if (indexIsFresh) {
    console.log(`Creating index '${SINGLE_INDEX_NAME}'...`);
    await waitForSuccess(
      client.createIndex(SINGLE_INDEX_NAME, { primaryKey: 'slug' }),
      'Index creation'
    );
  } else {
    console.log(
      `Index '${SINGLE_INDEX_NAME}' already exists. Updating settings.`
    );
  }

  const index = client.index(SINGLE_INDEX_NAME);
  await waitForSuccess(
    index.updateSettings(COMMON_INDEX_SETTINGS),
    'Settings update'
  );

  console.log(
    `Indexing ${allDocumentsToIndex.length} document(s) into '${SINGLE_INDEX_NAME}'...`
  );
  await waitForSuccess(
    index.addDocuments(allDocumentsToIndex, { primaryKey: 'slug' }),
    'Document addition'
  );

  // A fresh index (just created, or just recreated by --reset) cannot have
  // any stale documents — only a pre-existing index in update mode can.
  if (!indexIsFresh) {
    // Belt-and-braces: with directory sources excluded from the generic
    // required loop, requiredDocuments is already service-only. The filter
    // makes the reconciler's contract explicit at the call site and stays
    // correct if another required source is added later.
    await reconcileStaleServiceDocuments(
      index,
      requiredDocuments.filter(d => d.type === 'service')
    );
    await reconcileStaleDirectoryDocuments(index, directorySnapshot);
  }

  console.log(
    `Meilisearch indexing script for '${SINGLE_INDEX_NAME}' finished successfully.`
  );
}

// Only runs when executed directly, never when required by a test — the
// same guard scripts/sync-talacms.ts uses for its ESM equivalent.
if (require.main === module) {
  main().catch(error => {
    console.error('Meilisearch indexing failed:', error);
    process.exitCode = 1;
  });
}

